const SVGNS = 'http://www.w3.org/2000/svg';
function el(tag, attrs, parent){ const e = document.createElementNS(SVGNS, tag); for (const k in attrs) e.setAttribute(k, attrs[k]); if (parent) parent.appendChild(e); return e; }
/* 포즈 하나를 그룹으로 만든다. s = 배율, sw = 화면에서 보일 선 굵기(px) */
function makePose(name, s, sw, parent, drawClass){
  const P = JOKE[name], k = P.k || 1, S = s * k;
  const g = el('g', {transform:`scale(${S}) translate(${-P.ox} ${-P.oy})`, 'data-pose':name}, parent);
  el('path', {d:P.fill, class:'paper'}, g);
  P.lines.forEach(d => el('path', {d, class:'jk'+(drawClass?' '+drawClass:''), style:`stroke-width:${sw/S}`}, g));
  el('circle', {cx:P.eye[0], cy:P.eye[1], r:5.5/k, fill:'var(--joke)'}, g);
  return g;
}
